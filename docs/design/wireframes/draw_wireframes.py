"""MES 低保真线框图生成器：8 个页面 PNG（1280x900）"""
import os
from PIL import Image, ImageDraw, ImageFont

OUT = "docs/design/wireframes/shots"
os.makedirs(OUT, exist_ok=True)
FONT = "/System/Library/Fonts/PingFang.ttc"
_REG = {}
_MED = {}
def F(sz, med=False):
    d = _MED if med else _REG
    if sz not in d:
        d[sz] = ImageFont.truetype(FONT, sz, index=5 if med else 2)
    return d[sz]

GRAY = "#666"; LIGHT = "#f4f6f8"; RED = "#c0392b"; GREEN = "#1e8449"; ORANGE = "#ca6f1e"

def new_page(title):
    img = Image.new("RGB", (1280, 900), "#e8e8e8")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, 1280, 44], fill="#2c3e50")
    d.text((16, 12), "MES 低保真原型 · " + title, font=F(16, True), fill="#cfe0f0")
    d.rectangle([24, 60, 1256, 876], outline="#999", fill="#ffffff", width=1)
    return img, d

def text(d, xy, s, size=14, fill="#333", med=False):
    d.text(xy, s, font=F(size, med), fill=fill)

def box(d, xy, fill="#fff", outline=GRAY, width=1):
    d.rectangle(xy, fill=fill, outline=outline, width=width)

def button(d, xy, label, kind="normal", size=13):
    x0, y0, x1, y1 = xy
    if kind == "primary":
        fill, oc, fc = "#3498db", "#2980b9", "#fff"
    elif kind == "warn":
        fill, oc, fc = "#e67e22", "#d35400", "#fff"
    elif kind == "danger":
        fill, oc, fc = "#e74c3c", "#c0392b", "#fff"
    else:
        fill, oc, fc = "#f0f0f0", "#777", "#333"
    d.rectangle([x0, y0, x1, y1], fill=fill, outline=oc, width=1)
    w = d.textlength(label, font=F(size))
    d.text(((x0+x1-w)/2, y0+4), label, font=F(size), fill=fc)

def tag(d, xy, label, color):
    x0, y0, x1, y1 = xy
    fillmap = {"green": ("#eafaf1", "#1e8449"), "orange": ("#fef5e7", "#ca6f1e"),
               "red": ("#fdedec", "#c0392b"), "gray": ("#f2f2f2", "#666")}
    fill, oc = fillmap.get(color, fillmap["gray"])
    d.rectangle([x0, y0, x1, y1], fill=fill, outline=oc, width=1)
    w = d.textlength(label, font=F(12))
    d.text(((x0+x1-w)/2, y0+2), label, font=F(12), fill=oc)

def table(d, x, y, headers, rows, col_w, row_h=30, rh=13):
    cx = x
    for i, h in enumerate(headers):
        box(d, [cx, y, cx+col_w[i], y+row_h], fill=LIGHT)
        d.text((cx+6, y+7), h, font=F(rh))
        cx += col_w[i]
    for ri, row in enumerate(rows):
        cy = y + row_h*(ri+1)
        cx = x
        for i, cell in enumerate(row):
            box(d, [cx, cy, cx+col_w[i], cy+row_h])
            d.text((cx+6, cy+7), str(cell), font=F(rh))
            cx += col_w[i]
    return y + row_h*(len(rows)+1)

def topbar(d, x, y, w, left, right=None):
    d.rectangle([x, y, x+w, y+34], fill="#ecf0f1", outline=GRAY, width=1)
    d.text((x+10, y+9), left, font=F(13))
    if right:
        d.text((x+w-10-d.textlength(right, font=F(13)), y+9), right, font=F(13), fill="#555")

def save(img, name):
    img.save(os.path.join(OUT, name))
    print("saved", name)

